
"""Run an interactive MCP assistant powered by Groq tool calling."""

import asyncio
import sys
from pathlib import Path

from groq import APIConnectionError, APIStatusError
from mcp import Client, StdioServerParameters

from agent import run_agent


BASE_DIR = Path(__file__).resolve().parent
SERVER_PATH = BASE_DIR / "server.py"


def display_response(
    answer: str,
    resources: list[str],
    prompts: list[str],
) -> None:
    """Display the agent response and selected MCP components.

    Args:
        answer (str): Final response generated by Groq.
        resources (list[str]): MCP resource URIs used by the agent.
        prompts (list[str]): MCP prompt names used by the agent.

    Returns:
        None: Prints the formatted response.

    Raises:
        None.
    """
    print("\nAI RESPONSE")
    print("-" * 40)
    print(answer)

    readable_resources = [
        uri.rsplit("/", 1)[-1].replace("_", " ").title()
        for uri in resources
    ]

    readable_prompts = [
        name.replace("_", " ").title()
        for name in prompts
    ]

    print("\n" + "-" * 40)
    print(f"Sources: {', '.join(readable_resources)}")
    print(f"Prompt: {', '.join(readable_prompts)}")
    print("=" * 40)


async def main() -> None:
    """Start the MCP client and handle interactive user questions.

    Args:
        None.

    Returns:
        None: Runs the terminal-based assistant until the user exits.

    Raises:
        RuntimeError: If establishing the MCP session fails.
    """
    server = StdioServerParameters(
        command=sys.executable,
        args=[str(SERVER_PATH)],
    )

    async with Client(server) as client:
        print("\n" + "=" * 40)
        print("          MCP AI ASSISTANT")
        print("=" * 40)
        print("Connected successfully.")
        print("Ask a question about the project.")
        print("Type 'exit' to quit.")

        while True:
            try:
                question = await asyncio.to_thread(
                    input,
                    "\nYou: ",
                )

            except (KeyboardInterrupt, EOFError):
                print("\nSession ended.")
                break

            question = question.strip()

            if question.lower() in {"exit", "quit"}:
                print("\nSession ended.")
                break

            if not question:
                continue

            try:
                answer, resources, prompts = await run_agent(
                    client=client,
                    question=question,
                )

                display_response(
                    answer=answer,
                    resources=resources,
                    prompts=prompts,
                )

            except APIStatusError as exc:
                print(
                    f"\nGroq API Error: HTTP {exc.status_code}"
                )
                print(exc.response.text[:2000])

            except APIConnectionError as exc:
                print(f"\nGroq Connection Error: {exc}")

            except (ValueError, RuntimeError) as exc:
                print(f"\nAssistant Error: {exc}")


if __name__ == "__main__":
    asyncio.run(main())
